# Day-07: String Indexing and Slicing
text = "Python"
print("First character:", text[0])
print("Last character:", text[-1])
print("First three:", text[:3])
print("From index 2:", text[2:])
print("Reverse:", text[::-1])

# Output:
# First character: P
# Last character: n
# First three: Pyt
# From index 2: thon
# Reverse: nohtyP
