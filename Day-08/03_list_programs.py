# Day-08: List Programs
numbers = [12, 5, 20, 8, 3]
print("Length:", len(numbers))
print("Maximum:", max(numbers))
print("Minimum:", min(numbers))
print("Sum:", sum(numbers))
print("Ascending:", sorted(numbers))

# Output:
# Length: 5
# Maximum: 20
# Minimum: 3
# Sum: 48
# Ascending: [3, 5, 8, 12, 20]
