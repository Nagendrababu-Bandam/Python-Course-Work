# Day-03: Basic Data Types
age = 22                 # int
price = 99.5             # float
name = "Nagendra"         # str
is_learning = True        # bool
numbers = [1, 2, 3]       # list
colors = ("red", "blue")  # tuple
unique_numbers = {1, 2}  # set
student = {"name": "Ravi", "age": 20}  # dict
nothing = None            # NoneType

print(type(age))
print(type(price))
print(type(name))
print(type(is_learning))
print(type(numbers))
print(type(colors))
print(type(unique_numbers))
print(type(student))
print(type(nothing))

# Output:
# <class 'int'>
# <class 'float'>
# <class 'str'>
# <class 'bool'>
# <class 'list'>
# <class 'tuple'>
# <class 'set'>
# <class 'dict'>
# <class 'NoneType'>
