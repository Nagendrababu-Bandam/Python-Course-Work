# Day-03: Basic Type Conversion
number_text = "25"
number = int(number_text)
decimal_number = float(number_text)
text_again = str(number)

print(number, type(number))
print(decimal_number, type(decimal_number))
print(text_again, type(text_again))

# Output:
# 25 <class 'int'>
# 25.0 <class 'float'>
# 25 <class 'str'>
