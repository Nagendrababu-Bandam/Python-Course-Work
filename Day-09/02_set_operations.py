# Day-09: Set Operations
a = {1, 2, 3}
b = {3, 4, 5}
print("Union:", a | b)
print("Intersection:", a & b)
print("Difference:", a - b)
print("Symmetric difference:", a ^ b)

# Sample Output (set order may vary):
# Union: {1, 2, 3, 4, 5}
# Intersection: {3}
# Difference: {1, 2}
# Symmetric difference: {1, 2, 4, 5}
