# =====  Logical Operators  =======
# Used to combine conditions.

# Operators: and, or, not

a = 10
b = 5

print(a > 5 and b < 10)
print(a > 15 or b < 10)
print(not(a > 5))

# Output:
# True
# True
# False

# and: Both conditions must be true.
# or: At least one condition must be true.
# not: Reverses the result.