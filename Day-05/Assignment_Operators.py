# Assignment Operators
# Used to assign or update a variable's value.

# Operators: =, +=, -=, *=, /=, %=, //=, **=

a = 10

print("Original:", a)

a += 5
print("After +=:", a)

a -= 3
print("After -=:", a)

a *= 2
print("After *=:", a)

a /= 4
print("After /=:", a)

# Output:
# Original: 10
# After +=: 15
# After -=: 12
# After *=: 24
# After /=: 6.0