# Comparison Operators
# Used to compare two values. The result is True or False.

# Operators: ==, !=, >, <, >=, <=

a = 10
b = 5
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

# Output:
# False
# True
# True
# False
# True
# False


# Remember:
#  > means greater than.
#  < means less than.
#  == means equal to.
#  != means not equal to.