# Bitwise Operators
# Used to perform operations on the binary bits of integers.

# Operators: &, |, ^, ~, <<, >>

a = 5
b = 3

print("AND:", a & b)
print("OR:", a | b)
print("XOR:", a ^ b)
print("NOT:", ~a)
print("Left Shift:", a << 1)
print("Right Shift:", a >> 1)

# Output:
# AND: 1
# OR: 7
# XOR: 6
# NOT: -6
# Left Shift: 10
# Right Shift: 2